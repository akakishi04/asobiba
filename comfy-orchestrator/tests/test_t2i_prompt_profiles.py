"""Offline regressions for versioned T2I prompt generation.

Proves the legacy baseline is unchanged and the enhanced Illustrious policy
is sent to LM Studio without altering JSON schema, VRAM lifecycle, or I2I.
"""

from __future__ import annotations

import copy
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from comfy_orchestrator import core, gui, lmstudio, prompt_profiles
from comfy_orchestrator.history import HistoryStore


ROOT = Path(__file__).resolve().parents[1]


LEGACY_SYSTEM = (
    "You are a fixed ComfyUI workflow selector. Output JSON matching the provided schema. "
    "Select workflow_id only from the catalog. Never invent nodes, paths, or model names. "
    "Write a detailed positive_prompt suitable for the image-generation model; "
    "use short comma-separated English visual tags for anime-style SDXL workflows. "
    "Keep instructions faithful to the user's request. "
    "Only supply parameters supported by the selected workflow. "
    "Never provide a seed: it is generated by the application or set by the user. "
    "If the source image is not provided to the LLM, do not invent visual facts about it. "
)


class PromptProfileTests(unittest.TestCase):
    def setUp(self):
        self.config = core.load_config(ROOT / "config.example.json")
        self.t2i = {
            "wai_t2i_basic": self.config["workflows"]["wai_t2i_basic"]
        }
        self.i2i = {
            "wai_i2i_basic": self.config["workflows"]["wai_i2i_basic"]
        }

    def test_default_is_enhanced_illustrious_v2(self):
        self.assertEqual(
            self.config["llm"]["t2i_prompt_profile"], "illustrious_v2"
        )
        self.assertIn("legacy", prompt_profiles.T2I_PROFILES)
        self.assertEqual(
            set(prompt_profiles.T2I_LABEL_TO_PROFILE.values()),
            set(prompt_profiles.T2I_PROFILES),
        )

    def test_legacy_system_prompt_is_unmodified(self):
        text = prompt_profiles.apply_t2i_profile(
            LEGACY_SYSTEM, self.t2i, "legacy"
        )
        self.assertEqual(text, LEGACY_SYSTEM)

    def test_enhanced_policy_has_specific_and_nonconflicting_rules(self):
        enhanced = prompt_profiles.apply_t2i_profile(
            LEGACY_SYSTEM, self.t2i, "illustrious_v2"
        )
        self.assertTrue(enhanced.startswith(LEGACY_SYSTEM))
        for expected in (
            "waiIllustrious SDXL v1.7",
            "subject count",
            "camera angle and framing",
            "light direction",
            "fabric folds",
            "Negative_prompt should be SHORT",
            "do NOT",
        ):
            self.assertIn(expected.lower(), enhanced.lower())
        self.assertGreater(len(enhanced), len(LEGACY_SYSTEM))

    def test_non_t2i_modes_keep_previous_system_prompt(self):
        for key in ("wai_i2i_basic", "wai_inpaint_basic",
                    "wai_pose_skeleton", "wai_pose_detect"):
            with self.subTest(key=key):
                workflow = {key: self.config["workflows"][key]}
                self.assertEqual(
                    prompt_profiles.apply_t2i_profile(
                        LEGACY_SYSTEM, workflow, "illustrious_v2"
                    ),
                    LEGACY_SYSTEM,
                )

    def test_unrelated_t2i_models_do_not_receive_illustrious_rules(self):
        unrelated = {
            "qwen_t2i": {
                "kind": "t2i",
                "description": "Qwen Image general text-to-image workflow",
                "bindings": {"positive_prompt": {"node": "8", "input": "text"}},
            }
        }
        self.assertFalse(prompt_profiles.is_t2i_context(unrelated))
        self.assertEqual(
            prompt_profiles.apply_t2i_profile(
                LEGACY_SYSTEM, unrelated, "illustrious_v2"
            ),
            LEGACY_SYSTEM,
        )

    def test_unexpected_profile_is_rejected(self):
        with self.assertRaises(ValueError):
            prompt_profiles.apply_t2i_profile(
                LEGACY_SYSTEM, self.t2i, "not-a-profile"
            )

    def _one_interpret(self, profile, workflows=None, image=None):
        settings = dict(
            self.config["llm"],
            t2i_prompt_profile=profile,
            model="unit-test-local-model",
        )
        workflows = self.t2i if workflows is None else workflows
        answer = {
            "workflow_id": next(iter(workflows)),
            "parameters": {
                "positive_prompt": "1girl, solo, silver hair, standing, sunset"
            },
        }
        requests = []
        progress = []

        def fake_request(_settings, route, payload=None):
            requests.append((route, payload))
            if route == "/v1/chat/completions":
                return {"choices": [{"message": {"content": json.dumps(answer)}}]}
            if route == "/api/v1/models/unload":
                return {"instance_id": "profile-instance"}
            raise AssertionError(route)

        with patch.object(
            lmstudio.LMStudio, "_ensure_loaded", return_value="profile-instance"
        ), patch.object(lmstudio, "_request", side_effect=fake_request):
            actual = lmstudio.LMStudio(settings).interpret(
                "夕暮れの海に立つ銀髪の少女", workflows, image,
                progress=progress.append,
            )
        self.assertEqual(actual, answer)
        self.assertEqual(
            [route for route, _ in requests],
            ["/v1/chat/completions", "/api/v1/models/unload"],
        )
        return requests[0][1], progress

    def test_comparable_profiles_keep_request_schema_and_temperature(self):
        enhanced, logs = self._one_interpret("illustrious_v2")
        baseline, legacy_logs = self._one_interpret("legacy")
        self.assertEqual(
            baseline["messages"][0]["content"], LEGACY_SYSTEM
        )
        self.assertIn(
            "waiIllustrious SDXL v1.7", enhanced["messages"][0]["content"]
        )
        self.assertEqual(
            enhanced["response_format"], baseline["response_format"]
        )
        self.assertEqual(enhanced["temperature"], baseline["temperature"])
        self.assertEqual(enhanced["max_tokens"], baseline["max_tokens"])
        self.assertEqual(
            enhanced["messages"][1]["content"].split("User request: ")[-1],
            baseline["messages"][1]["content"].split("User request: ")[-1],
        )
        self.assertIn(
            "Reference role: none (text-to-image)",
            enhanced["messages"][1]["content"],
        )
        self.assertIn(
            "Reference role: composition of image to edit",
            baseline["messages"][1]["content"],
        )
        self.assertTrue(any("Illustrious v2" in p for p in logs))
        self.assertTrue(any("従来版" in p for p in legacy_logs))

    def test_core_rejects_invalid_saved_profile(self):
        cfg = copy.deepcopy(self.config)
        cfg["llm"]["t2i_prompt_profile"] = "invalid"
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "config.json"
            path.write_text(json.dumps(cfg), encoding="utf-8")
            with self.assertRaisesRegex(core.OrchestratorError, "t2i_prompt_profile"):
                core.load_config(path)

    def test_bootstrap_migrates_old_settings_without_changing_other_options(self):
        cfg = copy.deepcopy(self.config)
        cfg["llm"].pop("t2i_prompt_profile")
        cfg["llm"]["model"] = "saved-local-model"
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "config.json"
            path.write_text(json.dumps(cfg), encoding="utf-8")
            with patch.object(gui, "CONFIG", path):
                migrated = gui.bootstrap_config()
            self.assertEqual(
                migrated["llm"]["t2i_prompt_profile"], "illustrious_v2"
            )
            self.assertEqual(migrated["llm"]["model"], "saved-local-model")

    def test_history_records_prompt_profile_without_altering_generation_params(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            store = HistoryStore(root)
            image = store.outputs / "example.png"
            image.write_bytes(b"fake output image")
            entry = store.record(
                prompt_id="profile-1", workflow_id="wai_t2i_basic",
                kind="t2i", request_text="銀髪の少女",
                parameters={"positive_prompt": "1girl, silver hair", "seed": 123},
                images=[image], prompt_profile="illustrious_v2",
            )
            retrieved = HistoryStore(root).get(entry.id)
            self.assertEqual(retrieved.prompt_profile, "illustrious_v2")
            self.assertEqual(retrieved.parameters, entry.parameters)
            self.assertNotIn("t2i_prompt_profile", retrieved.parameters)

    def test_gui_exposes_readonly_prompt_version_and_inspector(self):
        import inspect
        source = inspect.getsource(gui.Application._build)
        self.assertIn("self.t2i_profile_box", source)
        self.assertIn("state=\"readonly\"", source)
        self.assertIn('self.result_prompt_button', source)
        self.assertIn('command=self._show_prompt_preview', source)
        self.assertTrue(
            callable(getattr(gui.Application, "_show_prompt_preview", None))
        )


if __name__ == "__main__":
    unittest.main()
